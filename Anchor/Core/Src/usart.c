bool uartIdle = false;
//	Called from DMA To Idle mode
void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t Size)
{
	if (huart->Instance == USART6 || huart->Instance == USART3)
	{
		dwmInfo.uart_income = true;
		//	send back the bytes RX'ed for timing debug.
		UART_RX_len = Size;
		uartIdle = true;
	}
}





//	Called from Main Loop
int UART_GetMessage(uint8_t *buff, uint32_t buff_len) {
	uint32_t RetVal = 0;
	if (uartIdle)
	{
		memcpy((void*) buff, (const void*) UART_Buff, (size_t) UART_RX_len);

		//	Maintain DMA
		if (HW_Version == 1 || HW_Version == 2)
			HAL_UARTEx_ReceiveToIdle_DMA(&huart6, UART_Buff, sizeof(UART_Buff)); // Start receiving the next byte of data
		else if (HW_Version == 0)
			HAL_UARTEx_ReceiveToIdle_DMA(&huart3, UART_Buff, sizeof(UART_Buff)); // Start receiving the next byte of data
		//	Maintain Data structures
		uartIdle = false;
		dwmInfo.uart_income = false;
		RetVal = UART_RX_len;
		UART_RX_len = 0;
	}
	return RetVal;
}


void UART_SendMessage(void *buff, uint16_t buff_len){
	if (HW_Version == 1 || HW_Version == 2)
	  	HAL_UART_Transmit_DMA(&huart6, (uint8_t*) buff, buff_len);
	else if (HW_Version == 0)
		HAL_UART_Transmit_DMA(&huart3, (uint8_t*) buff, buff_len);
#ifdef TIMING_TESTS_USING_LED_GPIO
		HAL_GPIO_WritePin(SX_LED_TX_GPIO_Port, SX_LED_TX_Pin, GPIO_PIN_RESET);
#endif // TIMING_TESTS_USING_LED_GPIO
}

